export function getEffectiveAbbreviation(item, customOverrides = {}) {
  if (!item) return '';
  if (customOverrides[item.id]) return customOverrides[item.id];
  return item.airgate_abbreviation || item.caf_abbreviation;
}

export function getCatalogCategories() {
  const cats = new Set(AZURE_NAMING_CATALOG.map(c => c.category));
  return Array.from(cats).sort();
}

export function getCatalogScopes() {
  const scopes = new Set(AZURE_NAMING_CATALOG.map(c => c.scope));
  return Array.from(scopes).sort();
}
