export const AZURE_RESOURCE_CATALOG = BASE_RESOURCE_CATALOG.map((item) => {
  const match = AZURE_NAMING_CATALOG.find(
    (n) =>
      n.provider.toLowerCase() === item.resourceType?.toLowerCase() ||
      n.id.toLowerCase() === item.resourceType?.toLowerCase() ||
      n.airgate_abbreviation === item.abbreviation ||
      n.caf_abbreviation === item.abbreviation
  );
  return {
    ...item,
    minLength: item.minLength || (match ? match.minLength : 1),
    maxLength: item.maxLength || (match ? match.maxLength : 64),
    allowedCharacters:
      item.allowedCharacters ||
      (match ? match.allowedCharacters : "Alphanumerics and hyphens"),
    pattern:
      item.pattern ||
      (match
        ? match.pattern
        : `^[a-zA-Z0-9-_]{${item.minLength || 1},${item.maxLength || 64}}$`),
    scope: item.scope || (match ? match.scope : "Resource group"),
    taggable: item.taggable !== undefined ? item.taggable : (match ? match.taggable : true)
  };
});
